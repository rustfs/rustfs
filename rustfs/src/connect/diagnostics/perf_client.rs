fn signature_document(key: &DeviceIdentity, key_id: &str, envelope: &[u8]) -> Result<Vec<u8>, ClientPerformanceError> {
    let pkcs8 = key.to_pkcs8_der().map_err(|_| ClientPerformanceError::Signing)?;
    let signing_key = SigningKey::from_pkcs8_der(pkcs8.as_slice()).map_err(|_| ClientPerformanceError::Signing)?;
    let mut input = Vec::with_capacity(SIGNATURE_DOMAIN.len() + envelope.len());
    input.extend_from_slice(SIGNATURE_DOMAIN);
    input.extend_from_slice(envelope);
    let signature: Signature = signing_key.sign(&input);
    serde_json::to_vec(&ClientSignature {
        algorithm: "ES256",
        key_id,
        value: URL_SAFE_NO_PAD.encode_to_string(signature.normalize_s().to_bytes()),
    })
    .map_err(|_| ClientPerformanceError::Encoding)
}

fn archive(envelope: &[u8], signature: &[u8], result: &[u8]) -> Result<Vec<u8>, ClientPerformanceError> {
    let cursor = Cursor::new(Vec::with_capacity(envelope.len() + signature.len() + result.len() + 512));
    let mut writer = ZipWriter::new(cursor);
    let options = SimpleFileOptions::DEFAULT
        .compression_method(CompressionMethod::Stored)
        .unix_permissions(OUTPUT_MODE);
    for (name, bytes) in [(ENVELOPE_PATH, envelope), (SIGNATURE_PATH, signature), (RESULT_PATH, result)] {
        writer
            .start_file(name, options)
            .map_err(|_| ClientPerformanceError::Encoding)?;
        writer.write_all(bytes).map_err(ClientPerformanceError::Io)?;
    }
    writer
        .finish()
        .map(|cursor| cursor.into_inner())
        .map_err(|_| ClientPerformanceError::Encoding)
}

fn deployment_endpoint(value: &str) -> Result<Url, ClientPerformanceError> {
    let mut url = Url::parse(value).map_err(|_| ClientPerformanceError::InvalidEndpoint)?;
    let local_http = url.scheme() == "http"
        && url
            .host_str()
            .is_some_and(|host| host == "localhost" || host.parse::<std::net::IpAddr>().is_ok_and(|ip| ip.is_loopback()));
    if (url.scheme() != "https" && !local_http)
        || url.cannot_be_a_base()
        || !url.username().is_empty()
        || url.password().is_some()
        || url.query().is_some()
        || url.fragment().is_some()
    {
        return Err(ClientPerformanceError::InvalidEndpoint);
    }
    url.set_query(None);
    url.set_fragment(None);
    if !url.path().ends_with('/') {
        url.set_path(&format!("{}/", url.path()));
    }
    Ok(url)
}

fn proxy_url(value: &str) -> Result<Url, ClientPerformanceError> {
    let url = Url::parse(value).map_err(|_| ClientPerformanceError::InvalidProxy)?;
    if !matches!(url.scheme(), "http" | "https")
        || url.cannot_be_a_base()
        || !url.username().is_empty()
        || url.password().is_some()
        || url.query().is_some()
        || url.fragment().is_some()
    {
        return Err(ClientPerformanceError::InvalidProxy);
    }
    Ok(url)
}

fn resource_names_match(request: &ClientPerformanceRequest) -> bool {
    let Some(organization_uid) = request.organization_name.strip_prefix("organizations/") else {
        return false;
    };
    if !uuid7(organization_uid) {
        return false;
    }
    let cluster_prefix = format!("{}/clusters/", request.organization_name);
    let Some(cluster_uid) = request.cluster_name.strip_prefix(&cluster_prefix) else {
        return false;
    };
    if !uuid7(cluster_uid) {
        return false;
    }
    let device_prefix = format!("{}/clusterDevices/", request.cluster_name);
    request.device_name.strip_prefix(&device_prefix).is_some_and(uuid7)
}

fn uuid7(value: &str) -> bool {
    Uuid::parse_str(value).is_ok_and(|uuid| {
        uuid.get_version() == Some(Version::SortRand) && uuid.get_variant() == Variant::RFC4122 && uuid.to_string() == value
    })
}

fn lower_hex_string(value: &str, length: usize) -> bool {
    value.len() == length
        && value
            .bytes()
            .all(|byte| byte.is_ascii_hexdigit() && !byte.is_ascii_uppercase())
}

fn version(value: &str) -> bool {
    if value.is_empty() || value.len() > 64 {
        return false;
    }
    let (core, prerelease) = value
        .split_once('-')
        .map_or((value, None), |(core, prerelease)| (core, Some(prerelease)));
    let mut parts = core.split('.');
    let valid_core = (0..3).all(|_| {
        parts
            .next()
            .is_some_and(|part| !part.is_empty() && part.bytes().all(|byte| byte.is_ascii_digit()))
    }) && parts.next().is_none();
    valid_core
        && prerelease.is_none_or(|part| {
            !part.is_empty()
                && part
                    .bytes()
                    .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'-'))
        })
}

fn build_feature(value: &str) -> bool {
    value.len() <= 64
        && value.as_bytes().split_first().is_some_and(|(first, rest)| {
            first.is_ascii_lowercase()
                && rest
                    .iter()
                    .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || matches!(byte, b'-' | b'_'))
        })
}

fn elapsed_millis(duration: Duration) -> u64 {
    elapsed_millis_allow_zero(duration).max(1)
}

fn elapsed_millis_allow_zero(duration: Duration) -> u64 {
    u64::try_from(duration.as_millis()).unwrap_or(u64::MAX).min(MAX_SAFE_INTEGER)
}

fn elapsed_micros(duration: Duration) -> u64 {
    u64::try_from(duration.as_micros()).unwrap_or(u64::MAX).min(MAX_SAFE_INTEGER)
}

fn unix_now() -> Result<i64, ClientPerformanceError> {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_err(|_| ClientPerformanceError::InvalidRequest)
        .and_then(|duration| i64::try_from(duration.as_secs()).map_err(|_| ClientPerformanceError::InvalidRequest))
}

fn timestamp(unix: i64) -> Result<String, ClientPerformanceError> {
    OffsetDateTime::from_unix_timestamp(unix)
        .map_err(|_| ClientPerformanceError::InvalidRequest)?
        .format(&Rfc3339)
        .map_err(|_| ClientPerformanceError::Encoding)
}

fn check_cancel(cancel: &CancellationToken) -> Result<(), ClientPerformanceError> {
    if cancel.is_cancelled() {
        Err(ClientPerformanceError::Cancelled)
    } else {
        Ok(())
    }
}

fn hex_lower(bytes: &[u8]) -> String {
    let mut encoded = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        use std::fmt::Write as _;
        let _ = write!(encoded, "{byte:02x}");
    }
    encoded
}

fn map_create_error(error: std::io::Error) -> ClientPerformanceError {
    if error.kind() == std::io::ErrorKind::AlreadyExists {
        ClientPerformanceError::AlreadyExists
    } else {
        ClientPerformanceError::Io(error)
    }
}

fn map_publish_error(error: std::io::Error) -> ClientPerformanceError {
    if error.kind() == std::io::ErrorKind::AlreadyExists {
        ClientPerformanceError::AlreadyExists
    } else {
        ClientPerformanceError::Io(error)
    }
}
