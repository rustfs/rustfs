pub struct HttpClientProbe {
    endpoint: Url,
    client: Client,
    access_key: Zeroizing<String>,
    secret_key: Zeroizing<String>,
    session_token: Zeroizing<String>,
    proxy_configured: bool,
}

impl HttpClientProbe {
    pub fn new(
        endpoint: &str,
        root_ca_pem: Option<&[u8]>,
        proxy: Option<&str>,
        access_key: Zeroizing<String>,
        secret_key: Zeroizing<String>,
        session_token: Zeroizing<String>,
        timeout: Duration,
    ) -> Result<Self, ClientPerformanceError> {
        let endpoint = deployment_endpoint(endpoint)?;
        if access_key.is_empty() || secret_key.is_empty() {
            return Err(ClientPerformanceError::InvalidCredential);
        }
        let mut builder = Client::builder()
            .no_proxy()
            .redirect(reqwest::redirect::Policy::none())
            .timeout(timeout);
        if let Some(root_ca_pem) = root_ca_pem {
            let certificate =
                reqwest::Certificate::from_pem(root_ca_pem).map_err(|_| ClientPerformanceError::InvalidRootCertificate)?;
            builder = builder.add_root_certificate(certificate);
        }
        if let Some(proxy) = proxy {
            let proxy_url = proxy_url(proxy)?;
            builder = builder.proxy(reqwest::Proxy::all(proxy_url).map_err(|_| ClientPerformanceError::InvalidProxy)?);
        }
        let client = builder.build().map_err(|_| ClientPerformanceError::TransportConfiguration)?;
        Ok(Self {
            endpoint,
            client,
            access_key,
            secret_key,
            session_token,
            proxy_configured: proxy.is_some(),
        })
    }

    async fn execute(
        &self,
        request: &ClientPerformanceRequest,
        cancel: &CancellationToken,
    ) -> Result<ClientProbeMeasurement, ClientProbeError> {
        let started = Instant::now();
        let traffic_bytes = usize::try_from(request.traffic_bytes).map_err(|_| ClientProbeError::ProtocolFailure)?;
        let payload = match request.operation {
            ClientOperation::PutObject => Bytes::from(vec![0xa5; traffic_bytes]),
            ClientOperation::GetObject => Bytes::new(),
        };
        let mut url = self
            .endpoint
            .join(CLIENT_SPEEDTEST_PATH)
            .map_err(|_| ClientProbeError::ProtocolFailure)?;
        let method = match request.operation {
            ClientOperation::PutObject => Method::POST,
            ClientOperation::GetObject => {
                url.query_pairs_mut().append_pair("bytes", &request.traffic_bytes.to_string());
                Method::GET
            }
        };
        let payload_hash = hex_lower(&Sha256::digest(&payload));
        let unsigned = http::Request::builder()
            .method(method.clone())
            .uri(url.as_str())
            .header("x-amz-content-sha256", payload_hash)
            .body(())
            .map_err(|_| ClientProbeError::ProtocolFailure)?;
        let signed_headers = rustfs_signer::try_sign_v4_headers(
            unsigned.into_parts().0,
            i64::try_from(payload.len()).map_err(|_| ClientProbeError::ProtocolFailure)?,
            &self.access_key,
            &self.secret_key,
            &self.session_token,
            "us-east-1",
        )
        .map_err(|_| ClientProbeError::ProtocolFailure)?;
        let send = self.client.request(method, url).headers(signed_headers).body(payload).send();
        let response = tokio::select! {
            () = cancel.cancelled() => return Err(ClientProbeError::Cancelled),
            response = send => response.map_err(|error| self.transport_error(&error))?,
        };
        let status = response.status();
        if status == StatusCode::UNAUTHORIZED || status == StatusCode::FORBIDDEN {
            return Err(ClientProbeError::PermissionDenied);
        }
        if !status.is_success() {
            return Err(ClientProbeError::ProtocolFailure);
        }
        let transferred_bytes = match request.operation {
            ClientOperation::PutObject => {
                let body = self.read_response_body(response, MAX_CLIENT_RESPONSE_BYTES, cancel).await?;
                let response: ClientDevnullResponse =
                    serde_json::from_slice(&body).map_err(|_| ClientProbeError::ProtocolFailure)?;
                if !response.measured || response.kind != "client-devnull" || response.rx_bytes != request.traffic_bytes {
                    return Err(ClientProbeError::ProtocolFailure);
                }
                request.traffic_bytes
            }
            ClientOperation::GetObject => {
                let body = self.read_response_body(response, traffic_bytes, cancel).await?;
                let body_len = u64::try_from(body.len()).map_err(|_| ClientProbeError::ProtocolFailure)?;
                if body_len != request.traffic_bytes || body.iter().any(|byte| *byte != 0) {
                    return Err(ClientProbeError::ProtocolFailure);
                }
                body_len
            }
        };
        let latency = started.elapsed();
        Ok(ClientProbeMeasurement {
            transferred_bytes,
            duration: latency,
            latency,
        })
    }

    async fn read_response_body(
        &self,
        response: Response,
        max_bytes: usize,
        cancel: &CancellationToken,
    ) -> Result<Vec<u8>, ClientProbeError> {
        let max_bytes_u64 = u64::try_from(max_bytes).map_err(|_| ClientProbeError::ProtocolFailure)?;
        if response.content_length().is_some_and(|length| length > max_bytes_u64) {
            return Err(ClientProbeError::ProtocolFailure);
        }
        let mut body = Vec::with_capacity(max_bytes.min(MAX_CLIENT_RESPONSE_BYTES));
        let mut stream = response.bytes_stream();
        loop {
            let chunk = tokio::select! {
                () = cancel.cancelled() => return Err(ClientProbeError::Cancelled),
                chunk = stream.next() => chunk,
            };
            let Some(chunk) = chunk else {
                break;
            };
            let chunk = chunk.map_err(|error| self.transport_error(&error))?;
            let new_length = body.len().checked_add(chunk.len()).ok_or(ClientProbeError::ProtocolFailure)?;
            if new_length > max_bytes {
                return Err(ClientProbeError::ProtocolFailure);
            }
            body.extend_from_slice(&chunk);
        }
        Ok(body)
    }

    fn transport_error(&self, error: &reqwest::Error) -> ClientProbeError {
        if error.is_timeout() {
            ClientProbeError::TimedOut
        } else if self.proxy_configured {
            ClientProbeError::ProxyFailure
        } else if error.is_connect() {
            ClientProbeError::EndpointUnavailable
        } else {
            ClientProbeError::ProtocolFailure
        }
    }
}

impl ClientProbe for HttpClientProbe {
    fn probe<'a>(&'a self, request: &'a ClientPerformanceRequest, cancel: &'a CancellationToken) -> ClientProbeFuture<'a> {
        Box::pin(self.execute(request, cancel))
    }
}

