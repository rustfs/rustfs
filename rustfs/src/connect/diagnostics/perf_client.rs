pub async fn measure_client(
    request: &ClientPerformanceRequest,
    probe: &impl ClientProbe,
    cancel: &CancellationToken,
) -> Result<ClientMeasurement, ClientPerformanceError> {
    request.validate(unix_now()?)?;
    if CLIENT_COLLECTOR_ACTIVE
        .compare_exchange(false, true, Ordering::AcqRel, Ordering::Acquire)
        .is_err()
    {
        return Err(ClientPerformanceError::Busy);
    }
    let _guard = ActiveGuard;
    if cancel.is_cancelled() {
        return Ok(terminal_measurement(
            request,
            ClientOutcome::Cancelled,
            ClientReasonCode::Cancelled,
            ClientTargetReasonCode::Cancelled,
            Duration::ZERO,
        ));
    }
    let started = Instant::now();
    let deadline = tokio::time::sleep(request.duration);
    tokio::pin!(deadline);
    let probe = probe.probe(request, cancel);
    tokio::pin!(probe);
    let result = tokio::select! {
        () = cancel.cancelled() => Err(ClientProbeError::Cancelled),
        () = &mut deadline => Err(ClientProbeError::TimedOut),
        result = &mut probe => result,
    };
    Ok(match result {
        Ok(sample) if sample.transferred_bytes == request.traffic_bytes => success_measurement(request, sample),
        Ok(_) => failed_measurement(request, started.elapsed(), ClientTargetReasonCode::ProtocolFailure),
        Err(ClientProbeError::Cancelled) => terminal_measurement(
            request,
            ClientOutcome::Cancelled,
            ClientReasonCode::Cancelled,
            ClientTargetReasonCode::Cancelled,
            started.elapsed(),
        ),
        Err(error) => failed_measurement(request, started.elapsed(), target_reason(error)),
    })
}

pub fn sign_client_export(
    request: &ClientPerformanceRequest,
    measurement: &ClientMeasurement,
    key: &DeviceIdentity,
    cancel: &CancellationToken,
) -> Result<SignedClientExport, ClientPerformanceError> {
    request.validate(unix_now()?)?;
    check_cancel(cancel)?;
    let result = &measurement.result;
    if result.outcome != ClientOutcome::Succeeded
        || result.data.is_none()
        || result.run_uid != request.run_uid
        || result.schema_version != CLIENT_SCHEMA_VERSION
        || result.tool_id != CLIENT_TOOL_ID
        || result.capability != CLIENT_CAPABILITY
    {
        return Err(ClientPerformanceError::InvalidRequest);
    }
    let result_json = serde_json::to_vec(result).map_err(|_| ClientPerformanceError::Encoding)?;
    if result_json.is_empty() || result_json.len() > MAX_CLIENT_RESULT_BYTES {
        return Err(ClientPerformanceError::LimitExceeded);
    }
    let device_key_id = hex_lower(&Sha256::digest(key.public_key_der()));
    let result_sha256 = hex_lower(&Sha256::digest(&result_json));
    let envelope = ClientEnvelope {
        format_version: "rustfs.connect.diagnosticEnvelope/1",
        protocol_version: "v1",
        organization_name: &request.organization_name,
        cluster_name: &request.cluster_name,
        device_name: &request.device_name,
        run_uid: &request.run_uid,
        artifact_uid: &request.artifact_uid,
        tool_id: CLIENT_TOOL_ID,
        schema_version: CLIENT_SCHEMA_VERSION,
        classification: "L1",
        consent_uid: &request.consent.consent_uid,
        policy_revision: request.consent.policy_revision,
        produced_at: timestamp(request.produced_at_unix)?,
        expires_at: timestamp(request.expires_at_unix)?,
        nonce: URL_SAFE_NO_PAD.encode_to_string(request.nonce),
        device_key_id: &device_key_id,
        payload: ClientPayload {
            path: RESULT_PATH,
            media_type: "application/json",
            size_bytes: u64::try_from(result_json.len()).map_err(|_| ClientPerformanceError::LimitExceeded)?,
            sha256: &result_sha256,
        },
    };
    let envelope_json = serde_json::to_vec(&envelope).map_err(|_| ClientPerformanceError::Encoding)?;
    if envelope_json.is_empty() || envelope_json.len() > MAX_ENVELOPE_BYTES {
        return Err(ClientPerformanceError::LimitExceeded);
    }
    let envelope_signature = signature_document(key, &device_key_id, &envelope_json)?;
    let decompressed = result_json
        .len()
        .checked_add(envelope_json.len())
        .and_then(|size| size.checked_add(envelope_signature.len()))
        .ok_or(ClientPerformanceError::LimitExceeded)?;
    if decompressed > MAX_DECOMPRESSED_BYTES {
        return Err(ClientPerformanceError::LimitExceeded);
    }
    check_cancel(cancel)?;
    if unix_now()? >= request.expires_at_unix {
        return Err(ClientPerformanceError::Expired);
    }
    let archive_bytes = archive(&envelope_json, &envelope_signature, &result_json)?;
    if archive_bytes.len() > MAX_ARCHIVE_BYTES {
        return Err(ClientPerformanceError::LimitExceeded);
    }
    let archive_sha256 = hex_lower(&Sha256::digest(&archive_bytes));
    Ok(SignedClientExport {
        artifact_uid: request.artifact_uid.clone(),
        outcome: result.outcome,
        reason_code: result.reason_code,
        envelope_json,
        envelope_signature,
        result_json,
        archive_bytes,
        archive_sha256,
    })
}

pub fn save_signed_client_export(
    output: &Path,
    export: &SignedClientExport,
    cancel: &CancellationToken,
) -> Result<SavedClientExport, ClientPerformanceError> {
    check_cancel(cancel)?;
    if !uuid7(&export.artifact_uid) || export.archive_bytes.is_empty() {
        return Err(ClientPerformanceError::InvalidRequest);
    }
    if export.archive_bytes.len() > MAX_ARCHIVE_BYTES {
        return Err(ClientPerformanceError::LimitExceeded);
    }
    if hex_lower(&Sha256::digest(&export.archive_bytes)) != export.archive_sha256 {
        return Err(ClientPerformanceError::InvalidRequest);
    }
    let parent = output
        .parent()
        .filter(|path| !path.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."));
    let filename = output
        .file_name()
        .ok_or(ClientPerformanceError::InvalidRequest)?
        .to_string_lossy();
    let temporary = parent.join(format!(".{filename}.{}.partial", export.artifact_uid));
    let mut options = OpenOptions::new();
    options.write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt as _;
        options.mode(OUTPUT_MODE);
    }
    let mut file = options.open(&temporary).map_err(map_create_error)?;
    let saved = (|| {
        file.write_all(&export.archive_bytes).map_err(ClientPerformanceError::Io)?;
        check_cancel(cancel)?;
        file.sync_all().map_err(ClientPerformanceError::Io)?;
        check_cancel(cancel)?;
        fs::hard_link(&temporary, output).map_err(map_publish_error)?;
        fs::remove_file(&temporary).map_err(ClientPerformanceError::DurabilityAfterCommit)?;
        #[cfg(unix)]
        File::open(parent)
            .and_then(|directory| directory.sync_all())
            .map_err(ClientPerformanceError::DurabilityAfterCommit)?;
        Ok(SavedClientExport {
            artifact_uid: export.artifact_uid.clone(),
            archive_size_bytes: u64::try_from(export.archive_bytes.len()).map_err(|_| ClientPerformanceError::LimitExceeded)?,
            archive_sha256: export.archive_sha256.clone(),
        })
    })();
    if saved.is_err() {
        let _ = fs::remove_file(&temporary);
    }
    saved
}

pub fn validate_client_limits(duration: Duration, traffic_bytes: u64) -> Result<(), ClientPerformanceError> {
    if duration.is_zero()
        || duration.as_millis() == 0
        || duration > MAX_CLIENT_DURATION
        || traffic_bytes == 0
        || traffic_bytes > MAX_CLIENT_TRAFFIC_BYTES
    {
        return Err(ClientPerformanceError::LimitExceeded);
    }
    let bandwidth_budget = u64::try_from(
        u128::from(MAX_CLIENT_BANDWIDTH_BYTES_PER_SECOND)
            .checked_mul(duration.as_millis())
            .ok_or(ClientPerformanceError::LimitExceeded)?
            / 1_000,
    )
    .map_err(|_| ClientPerformanceError::LimitExceeded)?;
    if traffic_bytes > bandwidth_budget.max(1) {
        return Err(ClientPerformanceError::LimitExceeded);
    }
    Ok(())
}

pub fn read_protected_client_credential(path: &Path) -> Result<Zeroizing<String>, ClientPerformanceError> {
    let metadata = fs::symlink_metadata(path).map_err(ClientPerformanceError::Io)?;
    if metadata.file_type().is_symlink() || !metadata.is_file() {
        return Err(ClientPerformanceError::InvalidCredential);
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::{MetadataExt as _, OpenOptionsExt as _, PermissionsExt as _};
        if metadata.uid() != process_uid() || metadata.permissions().mode() & 0o077 != 0 {
            return Err(ClientPerformanceError::InvalidCredential);
        }
        let mut options = OpenOptions::new();
        options.read(true).custom_flags(libc::O_CLOEXEC | libc::O_NOFOLLOW);
        let mut file = options.open(path).map_err(ClientPerformanceError::Io)?;
        let opened = file.metadata().map_err(ClientPerformanceError::Io)?;
        if opened.dev() != metadata.dev() || opened.ino() != metadata.ino() {
            return Err(ClientPerformanceError::InvalidCredential);
        }
        read_credential_value(&mut file)
    }
    #[cfg(not(unix))]
    {
        let mut file = File::open(path).map_err(ClientPerformanceError::Io)?;
        read_credential_value(&mut file)
    }
}

fn read_credential_value(reader: &mut impl Read) -> Result<Zeroizing<String>, ClientPerformanceError> {
    let mut bytes = Vec::with_capacity(256);
    reader
        .take(4_097)
        .read_to_end(&mut bytes)
        .map_err(ClientPerformanceError::Io)?;
    if bytes.is_empty() || bytes.len() > 4_096 || bytes.contains(&0) {
        return Err(ClientPerformanceError::InvalidCredential);
    }
    while matches!(bytes.last(), Some(b'\n' | b'\r')) {
        bytes.pop();
    }
    let value = String::from_utf8(bytes).map_err(|_| ClientPerformanceError::InvalidCredential)?;
    if value.is_empty() || value.len() > 4_096 || value.trim() != value {
        return Err(ClientPerformanceError::InvalidCredential);
    }
    Ok(Zeroizing::new(value))
}

