//! Consent-bound local drive performance measurement and offline export.
//!
//! The benchmark writes generated bytes to a task-owned scratch directory,
//! reads and verifies them, and removes the scratch state before returning.
//! The read follows the write and therefore measures the filesystem's warm
//! page-cache-visible path. It is not reported as cold physical-media I/O;
//! RustFS does not expose a portable cache-bypass adapter for this producer.
//! Existing StorageInfo counters are deliberately not used because passive
//! observations are not evidence of an active read/write benchmark.

