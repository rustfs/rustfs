pub(crate) fn classify_io(error: &std::io::Error) -> DriveTargetReasonCode {
    match error.kind() {
        std::io::ErrorKind::PermissionDenied | std::io::ErrorKind::ReadOnlyFilesystem => DriveTargetReasonCode::PermissionDenied,
        std::io::ErrorKind::StorageFull | std::io::ErrorKind::FileTooLarge | std::io::ErrorKind::QuotaExceeded => {
            DriveTargetReasonCode::LimitExceeded
        }
        std::io::ErrorKind::NotFound | std::io::ErrorKind::NotADirectory => DriveTargetReasonCode::SourceUnavailable,
        _ => DriveTargetReasonCode::IoFailure,
    }
}

