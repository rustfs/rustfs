pub async fn measure_drive(
    request: &DrivePerformanceRequest,
    cancel: &CancellationToken,
) -> Result<DriveMeasurement, DrivePerformanceError> {
    request.validate(unix_now()?)?;
    if cancel.is_cancelled() {
        return Ok(terminal_measurement(
            request,
            DriveOutcome::Cancelled,
            DriveReasonCode::Cancelled,
            DriveTargetReasonCode::Cancelled,
            0,
        ));
    }
    let _lease = CollectorLease::acquire()?;
    let started = Instant::now();
    let deadline = tokio::time::Instant::now() + request.duration;
    let mut scratch = match ScratchGuard::create(request) {
        Ok(scratch) => scratch,
        Err(error) => return Ok(failed_measurement(request, started.elapsed(), classify_io(&error), 0, 0, 0)),
    };

    let measured = run_benchmark(request, &scratch, cancel, deadline).await;
    let cleanup = scratch.cleanup();
    let elapsed = started.elapsed().min(request.duration);
    if cleanup.is_err() {
        let (read_bytes, write_bytes, io_count) = match &measured {
            Ok(sample) => (sample.read_bytes, sample.write_bytes, sample.io_count),
            Err(_) => (0, 0, 0),
        };
        return Ok(failed_measurement(
            request,
            elapsed,
            DriveTargetReasonCode::CleanupFailed,
            read_bytes,
            write_bytes,
            io_count,
        ));
    }
    match measured {
        Ok(sample) => Ok(success_measurement(request, elapsed, sample)),
        Err(BenchmarkFailure::Cancelled) => Ok(terminal_measurement(
            request,
            DriveOutcome::Cancelled,
            DriveReasonCode::Cancelled,
            DriveTargetReasonCode::Cancelled,
            elapsed_millis_allow_zero(elapsed),
        )),
        Err(BenchmarkFailure::TimedOut) => Ok(failed_measurement(request, elapsed, DriveTargetReasonCode::TimedOut, 0, 0, 0)),
        Err(BenchmarkFailure::Verification) => {
            Ok(failed_measurement(request, elapsed, DriveTargetReasonCode::VerificationFailed, 0, 0, 0))
        }
        Err(BenchmarkFailure::Io(error)) => Ok(failed_measurement(request, elapsed, classify_io(&error), 0, 0, 0)),
    }
}

pub fn sign_drive_export(
    request: &DrivePerformanceRequest,
    measurement: &DriveMeasurement,
    key: &DeviceIdentity,
    cancel: &CancellationToken,
) -> Result<SignedDriveExport, DrivePerformanceError> {
    request.validate(unix_now()?)?;
    check_cancel(cancel)?;
    let result = &measurement.result;
    if result.outcome != DriveOutcome::Succeeded
        || result.data.is_none()
        || result.run_uid != request.run_uid
        || result.schema_version != DRIVE_SCHEMA_VERSION
        || result.tool_id != DRIVE_TOOL_ID
        || result.capability != DRIVE_CAPABILITY
    {
        return Err(DrivePerformanceError::InvalidRequest);
    }
    let result_json = serde_json::to_vec(result).map_err(|_| DrivePerformanceError::Encoding)?;
    if result_json.is_empty() || result_json.len() > MAX_RESULT_BYTES {
        return Err(DrivePerformanceError::LimitExceeded);
    }
    let device_key_id = hex_lower(&Sha256::digest(key.public_key_der()));
    let result_sha256 = hex_lower(&Sha256::digest(&result_json));
    let envelope = DriveEnvelope {
        format_version: "rustfs.connect.diagnosticEnvelope/1",
        protocol_version: "v1",
        organization_name: &request.organization_name,
        cluster_name: &request.cluster_name,
        device_name: &request.device_name,
        run_uid: &request.run_uid,
        artifact_uid: &request.artifact_uid,
        tool_id: DRIVE_TOOL_ID,
        schema_version: DRIVE_SCHEMA_VERSION,
        classification: "L1",
        consent_uid: &request.consent.consent_uid,
        policy_revision: request.consent.policy_revision,
        produced_at: timestamp(request.produced_at_unix)?,
        expires_at: timestamp(request.expires_at_unix)?,
        nonce: URL_SAFE_NO_PAD.encode_to_string(request.nonce),
        device_key_id: &device_key_id,
        payload: DrivePayload {
            path: RESULT_PATH,
            media_type: "application/json",
            size_bytes: result_json.len() as u64,
            sha256: &result_sha256,
        },
    };
    let envelope_json = serde_json::to_vec(&envelope).map_err(|_| DrivePerformanceError::Encoding)?;
    if envelope_json.is_empty() || envelope_json.len() > MAX_ENVELOPE_BYTES {
        return Err(DrivePerformanceError::LimitExceeded);
    }
    let envelope_signature = signature_document(key, &device_key_id, &envelope_json)?;
    let decompressed = result_json
        .len()
        .checked_add(envelope_json.len())
        .and_then(|size| size.checked_add(envelope_signature.len()))
        .ok_or(DrivePerformanceError::LimitExceeded)?;
    if decompressed > MAX_DECOMPRESSED_BYTES {
        return Err(DrivePerformanceError::LimitExceeded);
    }
    check_cancel(cancel)?;
    if unix_now()? >= request.expires_at_unix {
        return Err(DrivePerformanceError::Expired);
    }
    let archive_bytes = archive(&envelope_json, &envelope_signature, &result_json)?;
    if archive_bytes.len() > MAX_ARCHIVE_BYTES {
        return Err(DrivePerformanceError::LimitExceeded);
    }
    let archive_sha256 = hex_lower(&Sha256::digest(&archive_bytes));
    Ok(SignedDriveExport {
        artifact_uid: request.artifact_uid.clone(),
        outcome: result.outcome,
        reason_code: result.reason_code,
        envelope_json,
        envelope_signature,
        result_json,
        archive_bytes,
        archive_sha256,
    })
}

pub fn save_signed_drive_export(
    output: &Path,
    export: &SignedDriveExport,
    cancel: &CancellationToken,
) -> Result<SavedDriveExport, DrivePerformanceError> {
    check_cancel(cancel)?;
    if !uuid7(&export.artifact_uid) {
        return Err(DrivePerformanceError::InvalidRequest);
    }
    if export.archive_bytes.is_empty() {
        return Err(DrivePerformanceError::InvalidRequest);
    }
    if export.archive_bytes.len() > MAX_ARCHIVE_BYTES {
        return Err(DrivePerformanceError::LimitExceeded);
    }
    if hex_lower(&Sha256::digest(&export.archive_bytes)) != export.archive_sha256 {
        return Err(DrivePerformanceError::InvalidRequest);
    }
    let parent = output
        .parent()
        .filter(|path| !path.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."));
    let filename = output
        .file_name()
        .ok_or(DrivePerformanceError::InvalidRequest)?
        .to_string_lossy();
    let temporary = parent.join(format!(".{filename}.{}.partial", export.artifact_uid));
    let mut options = OpenOptions::new();
    options.write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt as _;
        options.mode(OUTPUT_MODE);
    }
    let mut file = options.open(&temporary).map_err(map_create_error)?;
    let saved = (|| {
        file.write_all(&export.archive_bytes).map_err(DrivePerformanceError::Io)?;
        check_cancel(cancel)?;
        file.sync_all().map_err(DrivePerformanceError::Io)?;
        check_cancel(cancel)?;
        fs::hard_link(&temporary, output).map_err(map_publish_error)?;
        fs::remove_file(&temporary).map_err(DrivePerformanceError::DurabilityAfterCommit)?;
        #[cfg(unix)]
        File::open(parent)
            .and_then(|directory| directory.sync_all())
            .map_err(DrivePerformanceError::DurabilityAfterCommit)?;
        Ok(SavedDriveExport {
            artifact_uid: export.artifact_uid.clone(),
            archive_size_bytes: export.archive_bytes.len() as u64,
            archive_sha256: export.archive_sha256.clone(),
        })
    })();
    if saved.is_err() {
        let _ = fs::remove_file(&temporary);
    }
    saved
}

impl DrivePerformanceRequest {
    fn validate(&self, now_unix: i64) -> Result<(), DrivePerformanceError> {
        if self.schema_version != DRIVE_SCHEMA_VERSION {
            return Err(DrivePerformanceError::UnsupportedVersion);
        }
        if self.capability != DRIVE_CAPABILITY {
            return Err(DrivePerformanceError::UnsupportedCapability);
        }
        if !self.consent.confirmed || self.consent.policy_revision == 0 {
            return Err(DrivePerformanceError::ConsentRequired);
        }
        if self.consent.expires_at_unix <= now_unix || self.expires_at_unix > self.consent.expires_at_unix {
            return Err(DrivePerformanceError::ConsentExpired);
        }
        let validity = self
            .expires_at_unix
            .checked_sub(self.produced_at_unix)
            .ok_or(DrivePerformanceError::Expired)?;
        if self.produced_at_unix > now_unix.saturating_add(MAX_FUTURE_SKEW_SECONDS)
            || validity <= 0
            || validity > MAX_VALIDITY_SECONDS
            || self.expires_at_unix <= now_unix
        {
            return Err(DrivePerformanceError::Expired);
        }
        validate_drive_limits(self.duration, self.scratch_bytes, self.block_bytes)?;
        if !uuid7(&self.run_uid)
            || !uuid7(&self.artifact_uid)
            || !uuid7(&self.consent.consent_uid)
            || !resource_names_match(self)
            || self.target_alias != "drive-1"
            || self.scratch_root.as_os_str().is_empty()
            || !lower_hex(&self.provenance.source_commit, 40)
            || !lower_hex(&self.provenance.executable_sha256, 64)
            || !version(&self.provenance.rustfs_version)
            || self.provenance.build_features.len() > MAX_BUILD_FEATURES
            || !self.provenance.build_features.iter().all(|value| build_feature(value))
        {
            return Err(DrivePerformanceError::InvalidRequest);
        }
        Ok(())
    }
}

pub fn validate_drive_limits(duration: Duration, scratch_bytes: u64, block_bytes: u64) -> Result<(), DrivePerformanceError> {
    if duration.is_zero()
        || duration > MAX_DRIVE_DURATION
        || scratch_bytes == 0
        || scratch_bytes > MAX_TEMPORARY_BYTES
        || block_bytes == 0
        || block_bytes > MAX_BLOCK_BYTES
        || block_bytes > scratch_bytes
    {
        return Err(DrivePerformanceError::LimitExceeded);
    }
    let io_bytes = scratch_bytes.checked_mul(2).ok_or(DrivePerformanceError::LimitExceeded)?;
    let blocks = scratch_bytes.div_ceil(block_bytes);
    let operations = blocks.checked_mul(2).ok_or(DrivePerformanceError::LimitExceeded)?;
    let bandwidth_budget = u64::try_from(
        u128::from(MAX_BANDWIDTH_BYTES_PER_SECOND)
            .checked_mul(duration.as_millis())
            .ok_or(DrivePerformanceError::LimitExceeded)?
            / 1_000,
    )
    .map_err(|_| DrivePerformanceError::LimitExceeded)?;
    if io_bytes > MAX_IO_BYTES || io_bytes > bandwidth_budget.max(1) || operations > MAX_OPERATIONS {
        return Err(DrivePerformanceError::LimitExceeded);
    }
    Ok(())
}

#[derive(Clone, Copy)]
struct BenchmarkSample {
    read_bytes: u64,
    write_bytes: u64,
    io_count: u64,
    read_latency: Duration,
    write_latency: Duration,
}

enum BenchmarkFailure {
    Cancelled,
    TimedOut,
    Verification,
    Io(std::io::Error),
}

async fn run_benchmark(
    request: &DrivePerformanceRequest,
    scratch: &ScratchGuard,
    cancel: &CancellationToken,
    deadline: tokio::time::Instant,
) -> Result<BenchmarkSample, BenchmarkFailure> {
    let std_file = scratch.open_file().map_err(BenchmarkFailure::Io)?;
    let mut file = tokio::fs::File::from_std(std_file);
    let block_size = usize::try_from(request.block_bytes).map_err(|_| BenchmarkFailure::Verification)?;
    let write_buffer = vec![0xa5; block_size];
    let mut remaining = request.scratch_bytes;
    let mut write_bytes = 0_u64;
    let mut io_count = 0_u64;
    let write_started = Instant::now();
    while remaining > 0 {
        let length = usize::try_from(remaining.min(request.block_bytes)).map_err(|_| BenchmarkFailure::Verification)?;
        cancellable(file.write_all(&write_buffer[..length]), cancel, deadline).await?;
        write_bytes = write_bytes.checked_add(length as u64).ok_or(BenchmarkFailure::Verification)?;
        io_count = io_count.checked_add(1).ok_or(BenchmarkFailure::Verification)?;
        remaining -= length as u64;
        tokio::task::yield_now().await;
    }
    cancellable(file.sync_all(), cancel, deadline).await?;
    let write_latency = write_started.elapsed();
    cancellable(file.seek(std::io::SeekFrom::Start(0)), cancel, deadline).await?;

    let mut read_buffer = vec![0_u8; block_size];
    remaining = request.scratch_bytes;
    let mut read_bytes = 0_u64;
    let read_started = Instant::now();
    while remaining > 0 {
        let length = usize::try_from(remaining.min(request.block_bytes)).map_err(|_| BenchmarkFailure::Verification)?;
        cancellable(file.read_exact(&mut read_buffer[..length]), cancel, deadline).await?;
        if read_buffer[..length] != write_buffer[..length] {
            return Err(BenchmarkFailure::Verification);
        }
        read_bytes = read_bytes.checked_add(length as u64).ok_or(BenchmarkFailure::Verification)?;
        io_count = io_count.checked_add(1).ok_or(BenchmarkFailure::Verification)?;
        remaining -= length as u64;
        tokio::task::yield_now().await;
    }
    let read_latency = read_started.elapsed();
    drop(file);
    if read_bytes != request.scratch_bytes || write_bytes != request.scratch_bytes || io_count > MAX_OPERATIONS {
        return Err(BenchmarkFailure::Verification);
    }
    Ok(BenchmarkSample {
        read_bytes,
        write_bytes,
        io_count,
        read_latency,
        write_latency,
    })
}

async fn cancellable<T, F>(
    operation: F,
    cancel: &CancellationToken,
    deadline: tokio::time::Instant,
) -> Result<T, BenchmarkFailure>
where
    F: std::future::Future<Output = std::io::Result<T>>,
{
    tokio::select! {
        () = cancel.cancelled() => Err(BenchmarkFailure::Cancelled),
        () = tokio::time::sleep_until(deadline) => Err(BenchmarkFailure::TimedOut),
        result = operation => result.map_err(BenchmarkFailure::Io),
    }
}

struct ScratchGuard {
    directory: PathBuf,
    file: PathBuf,
    active: bool,
}

impl ScratchGuard {
    fn create(request: &DrivePerformanceRequest) -> std::io::Result<Self> {
        let metadata = fs::symlink_metadata(&request.scratch_root)?;
        if metadata.file_type().is_symlink() || !metadata.is_dir() {
            return Err(std::io::Error::new(
                std::io::ErrorKind::NotADirectory,
                "drive benchmark scratch root must be a real directory",
            ));
        }
        let directory = request.scratch_root.join(format!("{SCRATCH_PREFIX}{}", request.artifact_uid));
        let mut builder = fs::DirBuilder::new();
        #[cfg(unix)]
        {
            use std::os::unix::fs::DirBuilderExt as _;
            builder.mode(SCRATCH_MODE);
        }
        builder.create(&directory)?;
        Ok(Self {
            file: directory.join("benchmark.bin"),
            directory,
            active: true,
        })
    }

    fn open_file(&self) -> std::io::Result<File> {
        let mut options = OpenOptions::new();
        options.read(true).write(true).create_new(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt as _;
            options.mode(OUTPUT_MODE);
        }
        options.open(&self.file)
    }

    fn cleanup(&mut self) -> std::io::Result<()> {
        match fs::remove_file(&self.file) {
            Ok(()) => {}
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
            Err(error) => return Err(error),
        }
        fs::remove_dir(&self.directory)?;
        self.active = false;
        Ok(())
    }
}

impl Drop for ScratchGuard {
    fn drop(&mut self) {
        if self.active {
            let _ = fs::remove_file(&self.file);
            let _ = fs::remove_dir(&self.directory);
        }
    }
}

pub(crate) struct CollectorLease;

impl CollectorLease {
    pub(crate) fn acquire() -> Result<Self, DrivePerformanceError> {
        DRIVE_COLLECTOR_ACTIVE
            .compare_exchange(false, true, Ordering::AcqRel, Ordering::Acquire)
            .map(|_| Self)
            .map_err(|_| DrivePerformanceError::Busy)
    }
}

impl Drop for CollectorLease {
    fn drop(&mut self) {
        DRIVE_COLLECTOR_ACTIVE.store(false, Ordering::Release);
    }
}

