"""Archive of a run: every HTTP exchange the harness made, kept below the run directory for the leak scans.

Importing this module installs two hooks. The exchange hook registers the secrets a request carries as canaries,
searches the full response for every canary known at that moment, and appends one record to
`archive/exchanges.jsonl`. The site-start hook registers the secrets a server process is started with.

What is kept: response headers and documents (errors, listings, admin answers) in full; of a larger object body
only its hash and its first and last bytes, since the full body was already searched in memory. What is never kept:
the value of a request header that carries a secret (a digest stands in for it), request bodies (hash and length
only), and any canary found in a response (a marker stands in for it, and the finding is recorded next to it).
"""

from __future__ import annotations

import base64
import datetime
import hashlib
import json
import re
import tempfile
from pathlib import Path

import harness as h
import observe
import scan

ARCHIVE_DIR = "archive"
EXCHANGES = "exchanges.jsonl"
MASTER_KEY_ENV = "RUSTFS_SSE_S3_MASTER_KEY"
KEY_DIR_ENV = "RUSTFS_KMS_KEY_DIR"
# A response body up to this size is kept in full; so is every error and every text document up to DOCUMENT_LIMIT.
SMALL_BODY = 4 * h.KIB
DOCUMENT_LIMIT = h.MIB
EDGE = 64
_DOCUMENT_TYPES = ("application/xml", "text/", "application/json")
# The fragments of an invalid master key value that count as a leak: its first 8 and 12 and its last 12 characters.
INVALID_VALUE_FRAGMENTS = (8, scan.FRAGMENT, -scan.FRAGMENT)
_SECRET_PARTS = re.compile(r"[:;,\s]+")

_count = 0
_handle = None
_handle_dir: Path | None = None
# Key directory of each site that runs a Local KMS backend, by site name.
_key_dirs: dict[str, Path] = {}


def is_secret_header(name: str) -> bool:
    return name.endswith("customer-key") or "token" in name


def redact_request_headers(headers: dict[str, str]) -> dict[str, str]:
    """Request headers as they may be written down: a secret value becomes a digest of itself."""
    return {name: (f"<redacted sha256:{hashlib.sha256(value.encode()).hexdigest()[:12]}>" if is_secret_header(name) else value)
            for name, value in headers.items()}


def _text(data: bytes) -> str:
    # Latin-1 maps every byte to one character, so the stored text can be searched again byte for byte.
    return data.decode("latin-1")


def harvest(exchange: dict, number: int, registry: scan.Registry) -> None:
    """Register the secrets this exchange introduces: customer keys it sent, a data key it was handed."""
    for name, value in exchange["request_headers"].items():
        if name.endswith("customer-key"):
            raw = scan.decode_base64(value)
            # A value that is not base64 of key material is a malformed header, not a key.
            if raw is not None and len(raw) >= scan.MIN_KEY_BYTES:
                registry.register_bytes(scan.KIND_SSEC, "request header", raw)
    if exchange["path"].endswith(scan.DATA_KEY_ENDPOINT) and exchange["status"] == 200:
        try:
            answer = json.loads(exchange["response_body"])
        except ValueError:
            return
        plaintext = answer.get("plaintext_key") if isinstance(answer, dict) else None
        if isinstance(plaintext, str):
            registry.register_text(scan.KIND_DATA_KEY, "generated by the admin API", plaintext, origin=number)


def _findings(number: int, path: str, parts: list[tuple[str, bytes]], registry: scan.Registry) -> tuple[list[dict], int]:
    """(findings, number of exempt occurrences) for the named parts of one response."""
    findings, exempt = [], 0
    for where, data in parts:
        for hit in registry.scan(data):
            if scan.is_exempt(hit, number, path, where):
                exempt += 1
                continue
            findings.append({"where": where, "kind": hit.canary.kind, "digest": hit.canary.digest,
                             "label": hit.canary.label, "spelling": hit.spelling, "partial": hit.partial,
                             "what": hit.describe()})
    return findings, exempt


def build_record(number: int, exchange: dict, registry: scan.Registry, context: dict | None = None) -> dict:
    """The archived form of one exchange, with what the scan of its full response found."""
    headers = exchange["response_headers"]
    body = exchange["response_body"] or b""
    request_body = exchange.get("request_body") or b""
    parts = [(f"header {name}", f"{name}: {value}".encode("latin-1", errors="replace")) for name, value in headers.items()]
    findings, exempt = _findings(number, exchange["path"], [*parts, ("body", body)], registry)

    content_type = headers.get("content-type", "")
    is_document = exchange["status"] >= 400 or content_type.startswith(_DOCUMENT_TYPES)
    stored_body: dict = {"length": len(body), "sha256": hashlib.sha256(body).hexdigest()}
    if len(body) <= SMALL_BODY or (is_document and len(body) <= DOCUMENT_LIMIT):
        stored_body["text"] = _text(registry.mask(body))
    else:
        stored_body["head"] = _text(registry.mask(body[:EDGE]))
        stored_body["tail"] = _text(registry.mask(body[-EDGE:]))
    context = context or {}
    return {
        "n": number,
        "at": datetime.datetime.now(datetime.UTC).isoformat(timespec="milliseconds"),
        "site": exchange["site"],
        "config": context.get("config", ""),
        "case": context.get("case", ""),
        "row": context.get("row", ""),
        "op": exchange["label"],
        "method": exchange["method"],
        "path": exchange["path"],
        "query": exchange["query"],
        "request_headers": redact_request_headers(exchange["request_headers"]),
        "request_body": {"length": len(request_body), "sha256": hashlib.sha256(request_body).hexdigest()},
        "status": exchange["status"],
        "response_headers": {name: registry.mask_text(value) for name, value in headers.items()},
        "response_body": stored_body,
        "findings": findings,
        "exempt": exempt,
    }


def rescan(record: dict, registry: scan.Registry) -> list[dict]:
    """Findings in a stored record for the canaries of `registry`, including those registered after it was written."""
    parts = [(f"header {name}", f"{name}: {value}".encode("latin-1", errors="replace"))
             for name, value in record["response_headers"].items()]
    stored = record["response_body"]
    for name in ("text", "head", "tail"):
        if name in stored:
            parts.append(("body", stored[name].encode("latin-1", errors="replace")))
    return _findings(record["n"], record["path"], parts, registry)[0]


def all_findings(record: dict, registry: scan.Registry) -> list[dict]:
    """What the scan at the time of the exchange found, plus what a scan of the stored record finds now."""
    out = list(record["findings"])
    seen = {(f["where"], f["digest"], f["spelling"]) for f in out}
    for finding in rescan(record, registry):
        if (finding["where"], finding["digest"], finding["spelling"]) not in seen:
            out.append(finding)
    return out


def finalize(run_dir: Path, registry: scan.Registry) -> list[dict]:
    """The archived records judged by every canary the run ended up with; the archive is rewritten to match.

    A response can repeat a secret the harness learns only later (a key file the server created). The scan at the
    time of the exchange could not know it, so the stored record is searched again; what that finds is added to
    the record and masked in the file, which then holds no canary in clear.
    """
    global _handle
    records = load(run_dir)
    changed = False
    for record in records:
        late = [finding for finding in all_findings(record, registry) if finding not in record["findings"]]
        if not late:
            continue
        changed = True
        record["findings"].extend(late)
        record["response_headers"] = {name: registry.mask_text(value) for name, value in record["response_headers"].items()}
        for name in ("text", "head", "tail"):
            if name in record["response_body"]:
                record["response_body"][name] = registry.mask_text(record["response_body"][name])
    if changed:
        if _handle is not None and _handle_dir == run_dir:
            _handle.close()
            _handle = None
        temporary = path_of(run_dir).with_suffix(".tmp")
        temporary.write_text("".join(json.dumps(record, sort_keys=True) + "\n" for record in records))
        temporary.replace(path_of(run_dir))
    return records


def locate(record: dict) -> str:
    """Where an archived exchange happened, for a report."""
    case = f"case {record['case']}" + (f" row {record['row']}" if record["row"] else "") if record["case"] else "outside a case"
    query = f"?{record['query']}" if record["query"] else ""
    return (f"exchange #{record['n']} (site {record['site']}, {case}: {record['op']} {record['method']} "
            f"{record['path']}{query} -> {record['status']})")


def path_of(run_dir: Path) -> Path:
    return run_dir / ARCHIVE_DIR / EXCHANGES


def load(run_dir: Path) -> list[dict]:
    path = path_of(run_dir)
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def harvest_key_files(registry: scan.Registry = scan.REGISTRY, run_dir: Path | None = None) -> int:
    """Register the key files of every Local KMS backend seen so far; returns how many files were read."""
    directories = set(_key_dirs.values())
    if run_dir is not None:
        directories.update(p for p in (run_dir / "sites").glob("*/kms-keys") if p.is_dir())
    return sum(registry.register_key_files(directory) for directory in sorted(directories))


