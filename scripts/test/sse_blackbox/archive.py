def _sample(path: str = "/bucket/object", status: int = 400, headers: dict | None = None, body: bytes = b"",
            request_headers: dict | None = None) -> dict:
    return {"site": "selftest", "label": "PutObject", "method": "PUT", "path": path, "query": "",
            "request_headers": request_headers or {}, "request_body": b"", "status": status,
            "response_headers": headers or {}, "response_body": body}


def selftest() -> list[str]:
    """What the leak scans must report, what they must not, and the one occurrence they must accept."""
    failures = []
    # A key whose two base64 spellings differ, so each is told apart.
    key = next(k for k in (h.derived_key(f"selftest canary {i}") for i in range(200))
               if base64.b64encode(k) != base64.urlsafe_b64encode(k))
    spellings = {"base64": base64.b64encode(key).decode(), "base64url": base64.urlsafe_b64encode(key).decode(),
                 "hex": key.hex()}
    registry = scan.Registry()
    registry.register_bytes(scan.KIND_SSEC, "selftest", key)

    for name, text in spellings.items():
        samples = {"body": _sample(body=f"<Error><Code>InvalidRequest</Code><Message>bad key {text}</Message></Error>".encode()),
                   "header": _sample(headers={"x-echo": text})}
        for where, sample in samples.items():
            record = build_record(1, sample, registry)
            if not any(f["spelling"] == name and not f["partial"] for f in all_findings(record, registry)):
                failures.append(f"leak scan: a canary in its {name} spelling in a response {where} is not reported")
            if text.rstrip("=") in json.dumps(record):
                failures.append(f"archive: a canary found in a response {where} is written to the archive in clear")
            # The same response archived before the secret was known is found by the scan of what was stored.
            late = scan.Registry()
            stored = json.loads(json.dumps(build_record(1, sample, late)))
            late.register_bytes(scan.KIND_SSEC, "selftest", key)
            if not any(f["spelling"] == name for f in all_findings(stored, late)):
                failures.append(f"leak scan: a canary registered after the response was archived is not found ({name}, {where})")

    clean = _sample(headers={f"{h.SSEC}key-md5": h.key_md5(key), "etag": '"0123456789abcdef0123456789abcdef"'},
                    body=b"<Error><Code>AccessDenied</Code><Message>Access Denied</Message></Error>")
    if all_findings(build_record(1, clean, registry), registry):
        failures.append("leak scan: a response without a canary is reported (the MD5 of a key is not the key)")

    fragment = _sample(body=f"key starts with {spellings['base64'][:scan.FRAGMENT]}...".encode())
    if not any(f["partial"] for f in all_findings(build_record(1, fragment, registry), registry)):
        failures.append(f"leak scan: the first {scan.FRAGMENT} characters of a canary are not reported")

    harvested = scan.Registry()
    sent = _sample(status=200, request_headers=h.ssec(key))
    harvest(sent, 1, harvested)
    if len(harvested) != 1 or not harvested.scan(spellings["hex"].encode()):
        failures.append("archive: a customer key sent in a request header is not registered as a canary")
    if spellings["base64"].rstrip("=") in json.dumps(build_record(1, sent, harvested)):
        failures.append("archive: a customer key sent in a request header is written to the archive in clear")

    # The exemption: a generated data key, in the body of the response that returned it, and nowhere else.
    data_key = h.derived_key("selftest data key")
    encoded = base64.b64encode(data_key).decode()
    endpoint = f"{h.ADMIN_PREFIX}{scan.DATA_KEY_ENDPOINT}"
    answer = _sample(path=endpoint, status=200, headers={"content-type": "application/json"},
                     body=json.dumps({"key_id": "k", "plaintext_key": encoded, "ciphertext_blob": "AAAA"}).encode())
    exempting = scan.Registry()
    exempting.register_bytes(scan.KIND_SSEC, "selftest", key)
    harvest(answer, 7, exempting)
    record = build_record(7, answer, exempting)
    if all_findings(record, exempting) or record["exempt"] < 1:
        failures.append("leak scan: the data key in the response that returned it is not exempt")
    if encoded.rstrip("=") in json.dumps(record):
        failures.append("archive: a generated data key is written to the archive in clear")
    not_exempt = {
        "the data key in a later response of another endpoint":
            (8, _sample(body=f"<Error><Message>{encoded}</Message></Error>".encode())),
        "the data key in a later response of the same endpoint": (9, answer),
        "the data key in a header of the response that returned it": (7, {**answer, "response_headers": {"x-echo": encoded}}),
        "a customer key in a response of the data key endpoint": (7, {**answer, "response_body": spellings["base64"].encode()}),
    }
    for name, (number, sample) in not_exempt.items():
        if not all_findings(build_record(number, sample, exempting), exempting):
            failures.append(f"leak scan: {name} is not reported")

    invalid = scan.Registry()
    value = "zz#selftest-invalid-master-key#zz"
    invalid.register_text(scan.KIND_INVALID_MASTER_KEY, "selftest", value, fragments=INVALID_VALUE_FRAGMENTS)
    for name, text in (("first 8 characters", value[:8]), ("last 12 characters", value[-12:]), ("whole value", value)):
        if not invalid.scan(f"cannot parse '{text}'".encode()):
            failures.append(f"leak scan: the {name} of an invalid master key value are not reported")
    if invalid.scan(b"RUSTFS_SSE_S3_MASTER_KEY is not valid base64"):
        failures.append("leak scan: a message that repeats nothing of an invalid master key value is reported")

    # Secrets of a server's environment: a usable master key, an unusable one, a `name:secret` pair; nothing else.
    started = scan.Registry()
    secret = h.derived_key("selftest environment secret")
    register_environment("selftest", {
        MASTER_KEY_ENV: base64.b64encode(key).decode(),
        "RUSTFS_KMS_STATIC_SECRET_KEY": f"key-id:{base64.b64encode(secret).decode()}",
        "RUSTFS_KMS_KEY_DIR": "/a/directory/that/is/no/secret", "RUSTFS_KMS_ENABLE": "true"}, started)
    if started.kinds() != {scan.KIND_ENV_SECRET: 1, scan.KIND_MASTER_KEY: 1}:
        failures.append(f"environment secrets: registered {started.kinds()}, expected one master key and one other secret")
    if not started.scan(key.hex().encode()) or not started.scan(secret.hex().encode()):
        failures.append("environment secrets: a secret of the environment is not found in its hex spelling")
    if started.scan(b"key-id /a/directory/that/is/no/secret true"):
        failures.append("environment secrets: a value that is no secret is reported")
    refused = scan.Registry()
    register_environment("selftest", {MASTER_KEY_ENV: value}, refused)
    if refused.kinds() != {scan.KIND_INVALID_MASTER_KEY: 1} or not refused.scan(value[:8].encode()):
        failures.append("environment secrets: an unusable master key value is not registered with its fragments")

    with tempfile.TemporaryDirectory() as work:
        broken = scan.self_check(Path(work))
    if broken:
        failures.append(f"leak scan of files: {broken}")

    allowed = [h.SSE, h.SSE_KEY_ID, f"{h.SSEC}algorithm", f"{h.SSEC}key-md5", "etag", "x-amz-request-id",
               "x-amz-replication-status"]
    forbidden = ["x-rustfs-encryption-key", "x-rustfs-internal-inline-data", "x-minio-internal-server-side-encryption-iv",
                 "x-rustfs-replication-server-side-encryption-sealed-key", f"{h.SSEC}key", f"{h.COPY_SSEC}key"]
    if scan.internal_headers(allowed):
        failures.append(f"internal headers: public SSE headers are reported: {scan.internal_headers(allowed)}")
    if scan.internal_headers(forbidden) != sorted(forbidden):
        failures.append("internal headers: a storage-internal or customer-key header is not reported")

    generic = b"<Error><Code>InternalError</Code><Message>We encountered an internal error, please try again.</Message></Error>"
    telling = b"<Error><Code>InternalError</Code><Message>open /var/lib/kms/keys/a.key: permission denied</Message></Error>"
    if scan.internal_error_problem(generic):
        failures.append("500 messages: the generic internal error text is not accepted")
    if not scan.internal_error_problem(telling) or not scan.internal_error_problem(b"panicked at src/main.rs"):
        failures.append("500 messages: a 500 that names a path, or is not an error document, is accepted")
    return failures
