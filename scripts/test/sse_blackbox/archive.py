def register_environment(site_name: str, env: dict[str, str], registry: scan.Registry) -> None:
    """Register the secrets a server process is started with: every variable whose name marks it as one."""
    for name, value in env.items():
        if not any(marker in name for marker in h.SECRET_ENV_MARKERS) or not value.strip():
            continue
        label = f"{name} of site {site_name}"
        if name != MASTER_KEY_ENV:
            # A value can be a list or a `name:secret` pair; each part long enough to search for is a secret of its own.
            for part in _SECRET_PARTS.split(value.strip()):
                if len(part) >= scan.MIN_TEXT_SECRET:
                    registry.register_text(scan.KIND_ENV_SECRET, label, part)
            continue
        raw = scan.decode_base64(value)
        if raw is not None and len(raw) == 32:
            registry.register_bytes(scan.KIND_MASTER_KEY, label, raw)
        else:
            # The product must not repeat a value it refused to use, in whole or in part.
            registry.register_text(scan.KIND_INVALID_MASTER_KEY, label, value, fragments=INVALID_VALUE_FRAGMENTS)


def _on_site_start(site: h.Site, env: dict[str, str]) -> None:
    register_environment(site.name, env, scan.REGISTRY)
    if env.get(KEY_DIR_ENV):
        _key_dirs[site.name] = Path(env[KEY_DIR_ENV])
        scan.REGISTRY.register_key_files(_key_dirs[site.name])


def _on_exchange(exchange: dict) -> None:
    global _count, _handle, _handle_dir
    _count += 1
    harvest(exchange, _count, scan.REGISTRY)
    # A key the server created through the admin API exists as a file from this moment on.
    if exchange["method"] != "GET" and "/kms/" in exchange["path"] and exchange["site"] in _key_dirs:
        scan.REGISTRY.register_key_files(_key_dirs[exchange["site"]])
    if h.RUN_DIR is None:
        return
    if _handle is None or _handle_dir != h.RUN_DIR:
        target = path_of(h.RUN_DIR)
        target.parent.mkdir(parents=True, exist_ok=True)
        _handle, _handle_dir = target.open("a"), h.RUN_DIR
    record = build_record(_count, exchange, scan.REGISTRY, observe.context())
    _handle.write(json.dumps(record, sort_keys=True) + "\n")
    _handle.flush()


def install() -> None:
    if _on_exchange not in h.EXCHANGE_HOOKS:
        h.EXCHANGE_HOOKS.append(_on_exchange)
    if _on_site_start not in h.SITE_START_HOOKS:
        h.SITE_START_HOOKS.append(_on_site_start)


install()


